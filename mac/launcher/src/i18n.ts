let current: Lang = "pt-BR";

export function setLang(l: Lang) {
  current = l === "en" ? "en" : "pt-BR";
  document.documentElement.lang = current;
}

export function lang(): Lang {
  return current;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = (current === "pt-BR" ? ptBR[key] : undefined) ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** Fill every element carrying data-i18n="key" (and data-i18n-placeholder/-title). */
export function translateDom(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n as Key);
  });
  root.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder as Key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle as Key);
  });
}

