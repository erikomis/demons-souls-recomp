"""Lift the raw SPURS job binaries the runtime dumped (SPU_DUMP_MISS) and register them.

SPURS jobs are PIC code+data blobs that cellSpurs loads at LS 0 and enters at 0
(runtime/spu/spurs_job.c). The runtime looks them up by an FNV-1a-64 fingerprint of
the raw bytes, which the dump file name already carries (spujob_<FP>_<size>.bin).

For every dump in <miss_dir>:
  1. wrap the bytes as a minimal SPU ELF (base 0, entry 0)        -> <spu_dir>/job_images/
  2. spu_lifter --auto-functions under a per-job symbol prefix     -> <spu_dir>/job_<FP>/
  3. debase the lifted includes (bare "spu_context.h", like build_spu_workloads)
Then write <spu_dir>/jobmods_register.c, which the project template compiles when present.

usage: python tools/lift_spurs_jobs.py <ps3recomp> <miss_dir> <spu_dir>
"""
import os, re, subprocess, sys

ps3recomp, miss_dir, spu_dir = sys.argv[1:4]
sys.path.insert(0, os.path.join(ps3recomp, 'tools'))
from wrap_spu_elf import wrap                       # noqa: E402
from build_spu_workloads import debase_includes     # noqa: E402

FIRST_IMAGE_ID = 100        # clear of build_spu_workloads' ids (1..12) and lift_jobmods' (200+)
jobs = []
os.makedirs(os.path.join(spu_dir, 'job_images'), exist_ok=True)
for name in sorted(os.listdir(miss_dir)):
    m = re.fullmatch(r'spujob_([0-9A-F]{16})_(\d+)\.bin', name)
    if not m:
        continue
    fp, size = m.group(1), int(m.group(2))
    raw = open(os.path.join(miss_dir, name), 'rb').read()
    assert len(raw) == size, name
    tag = f'job_{fp}'
    elf = os.path.join(spu_dir, 'job_images', tag + '.elf')
    open(elf, 'wb').write(wrap(raw, base=0, entry=0))
    out = os.path.join(spu_dir, tag)
    os.makedirs(out, exist_ok=True)
    rc = subprocess.run([sys.executable, os.path.join(ps3recomp, 'tools', 'spu_lifter.py'), elf,
                         '--auto-functions', elf, '--symbol-prefix', tag + '_', '-o', out],
                        capture_output=True, text=True)
    if rc.returncode:
        sys.exit(f'lift failed for {name}:\n{rc.stdout}\n{rc.stderr}')
    debase_includes(os.path.join(out, 'spu_recomp.h'))
    debase_includes(os.path.join(out, 'spu_recomp.c'))
    funcs = re.findall(r'\n  (\d+) function\(s\) lifted', rc.stdout)
    print(f'{tag}: {size} bytes, {funcs[0] if funcs else "?"} functions')
    jobs.append((tag, fp))

L = ['/* Generated by DemonsSouls/tools/lift_spurs_jobs.py -- SPURS job binaries',
     ' * captured at run time with SPU_DUMP_MISS, keyed by raw-image fingerprint. */',
     '#include "spu_workload.h"', '', 'extern void spu_begin_image(int image_id);']
for tag, _ in jobs:
    L += [f'extern void {tag}_spu_func_00000000(spu_context*);',
          f'extern void {tag}_spu_recomp_register(void);']
L += ['', '__attribute__((constructor)) static void ds_jobs_register(void)', '{']
for i, (tag, fp) in enumerate(jobs):
    img = FIRST_IMAGE_ID + i
    L += [f'    spu_begin_image({img}); {tag}_spu_recomp_register();',
          f'    spu_workload_register_img(0x{fp}ULL, {tag}_spu_func_00000000, {img}, "{tag}");']
L += ['}', '']
open(os.path.join(spu_dir, 'jobmods_register.c'), 'w').write('\n'.join(L))
print(f'wrote jobmods_register.c ({len(jobs)} job(s))')
