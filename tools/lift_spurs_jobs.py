"""Lift the raw SPURS job binaries the runtime dumped (SPU_DUMP_MISS) and register them.

SPURS jobs are PIC code+data blobs that cellSpurs loads at LS 0 and enters at 0
(runtime/spu/spurs_job.c). The runtime looks them up by an FNV-1a-64 fingerprint of
the raw bytes, which the dump file name already carries (spujob_<FP>_<size>.bin).

For every dump in <miss_dir>:
  1. wrap the bytes as a minimal SPU ELF (base 0, entry 0)        -> <spu_dir>/job_images/
  2. spu_lifter --auto-functions under a per-job symbol prefix     -> <spu_dir>/job_<FP>/
  3. debase the lifted includes (bare "spu_context.h", like build_spu_workloads)
Then write <spu_dir>/jobmods_register.c, which the project template compiles when present.

usage: python tools/lift_spurs_jobs.py <ps3recomp> <miss_dir> <spu_dir>
"""
import argparse
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

FIRST_IMAGE_ID = 100  # 1..12 are embedded images; 200+ belongs to lift_jobmods.
MAX_JOB_SIZE = 256 * 1024


def fingerprint(raw):
    # Match spu_workload_fingerprint exactly, including its historical basis.
    h = 1469598103934665603
    for byte in raw:
        h = ((h ^ byte) * 1099511628211) & 0xffffffffffffffff
    return f'{h:016X}'


def read_jobs(miss_dir):
    jobs = []
    seen = set()
    for path in sorted(Path(miss_dir).iterdir()):
        match = re.fullmatch(r'spujob_([0-9A-F]{16})_(\d+)\.bin', path.name)
        if not match:
            continue
        fp, size = match[1], int(match[2])
        if not size or size > MAX_JOB_SIZE or size % 4:
            raise ValueError(f'{path.name}: job must contain 4..{MAX_JOB_SIZE} aligned bytes')
        with path.open('rb') as stream:
            raw = stream.read(size + 1)
        if len(raw) != size:
            raise ValueError(f'{path.name}: declared size does not match the dump')
        if fingerprint(raw) != fp:
            raise ValueError(f'{path.name}: fingerprint does not match the dump')
        if fp in seen:
            raise ValueError(f'{path.name}: duplicate job fingerprint')
        seen.add(fp)
        jobs.append((f'job_{fp}', fp, raw))
    if not jobs:
        raise ValueError('no SPU job dumps found; existing registrations were kept')
    if len(jobs) > 200 - FIRST_IMAGE_ID:
        raise ValueError('too many jobs: image IDs would overlap the reserved 200+ range')
    return jobs


def registration(jobs):
    lines = ['/* Generated by DemonsSouls/tools/lift_spurs_jobs.py -- SPURS job binaries',
             ' * captured at run time with SPU_DUMP_MISS, keyed by raw-image fingerprint. */',
             '#include "spu_workload.h"', '', 'extern void spu_begin_image(int image_id);']
    for tag, _, _ in jobs:
        lines += [f'extern void {tag}_spu_func_00000000(spu_context*);',
                  f'extern void {tag}_spu_recomp_register(void);']
    lines += ['', '__attribute__((constructor)) static void ds_jobs_register(void)', '{']
    for index, (tag, fp, _) in enumerate(jobs):
        image_id = FIRST_IMAGE_ID + index
        lines += [f'    spu_begin_image({image_id}); {tag}_spu_recomp_register();',
                  f'    spu_workload_register_img(0x{fp}ULL, {tag}_spu_func_00000000, {image_id}, "{tag}");']
    return '\n'.join(lines + ['}', ''])


def lift_jobs(ps3recomp, miss_dir, spu_dir):
    jobs = read_jobs(miss_dir)  # Validate every dump before changing generated output.
    sdk = Path(ps3recomp).resolve()
    sys.path.insert(0, str(sdk / 'tools'))
    from wrap_spu_elf import wrap
    from build_spu_workloads import debase_includes

    destination = Path(spu_dir)
    destination.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.job-lift-', dir=destination) as temporary:
        stage = Path(temporary)
        (stage / 'job_images').mkdir()
        for tag, _, raw in jobs:
            elf = stage / 'job_images' / (tag + '.elf')
            elf.write_bytes(wrap(raw, base=0, entry=0))
            output = stage / tag
            output.mkdir()
            result = subprocess.run([sys.executable, str(sdk / 'tools/spu_lifter.py'), str(elf),
                                     '--auto-functions', str(elf), '--symbol-prefix', tag + '_',
                                     '-o', str(output)], capture_output=True, text=True)
            if result.returncode:
                raise RuntimeError(f'lift failed for {tag}:\n{result.stdout}\n{result.stderr}')
            for name in ('spu_recomp.h', 'spu_recomp.c'):
                if not (output / name).is_file():
                    raise RuntimeError(f'{tag}: lifter did not produce {name}')
                debase_includes(str(output / name))
            if tag + '_spu_func_00000000' not in (output / 'spu_recomp.c').read_text():
                raise RuntimeError(f'{tag}: lifter did not produce the job entry at LS 0')
            print(f'{tag}: {len(raw)} bytes lifted')
        (stage / 'jobmods_register.c').write_text(registration(jobs))

        # Only publish once all jobs lifted successfully. Keep backups until the
        # final atomic registry replacement, rolling back failed filesystem moves.
        (destination / 'job_images').mkdir(exist_ok=True)
        backup = stage / 'backup'
        backup.mkdir()
        moved = []
        try:
            for tag, _, _ in jobs:
                for relative in (Path(tag), Path('job_images') / (tag + '.elf')):
                    target, source = destination / relative, stage / relative
                    old = backup / relative
                    old.parent.mkdir(parents=True, exist_ok=True)
                    existed = target.exists()
                    if existed:
                        os.replace(target, old)
                    moved.append((target, old, existed))
                    os.replace(source, target)
            os.replace(stage / 'jobmods_register.c', destination / 'jobmods_register.c')
        except OSError:
            import shutil
            for target, old, existed in reversed(moved):
                if target.is_dir():
                    shutil.rmtree(target)
                elif target.exists():
                    target.unlink()
                if existed:
                    os.replace(old, target)
            raise
    print(f'wrote jobmods_register.c ({len(jobs)} job(s))')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('ps3recomp')
    parser.add_argument('miss_dir')
    parser.add_argument('spu_dir')
    args = parser.parse_args(argv)
    try:
        lift_jobs(args.ps3recomp, args.miss_dir, args.spu_dir)
    except (OSError, ValueError, RuntimeError) as error:
        parser.exit(1, f'error: {error}\n')


if __name__ == '__main__':
    main()
